// Bakes the Phosphor icons the pages use into worker/runtime/http/pages/icons.ts,
// so pages need no icon font or script. Run `make icons` after changing NAMES.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const NAMES = ['calendar-blank', 'check-circle', 'door-open', 'dropbox-logo', 'eye', 'folder-simple-lock', 'google-logo', 'identification-card', 'image', 'notepad', 'plugs', 'plus', 'sign-out', 'stack', 'trash', 'user'];

const root = 'node_modules/@phosphor-icons/core';
const camel = (name) => name.replace(/-(\w)/gu, (_, c) => c.toUpperCase());
const lines = NAMES.map((name) => {
  const svg = readFileSync(join(root, 'assets', 'regular', `${name}.svg`), 'utf8').trim();
  const inner = svg.replace(/^<svg[^>]*>/u, '').replace(/<\/svg>$/u, '');
  return `  ${camel(name)}: '${inner.replaceAll("'", "\\'")}',`;
});
writeFileSync(
  'worker/runtime/http/pages/icons.ts',
  `// Generated by scripts/icons.mjs from @phosphor-icons/core (MIT). Do not edit.

const PATHS = {
${lines.join('\n')}
} as const;

export type IconName = keyof typeof PATHS;

export function icon(name: IconName, size = 24): string {
  return \`<svg class="icon" viewBox="0 0 256 256" width="\${size}" height="\${size}" fill="currentColor" aria-hidden="true">\${PATHS[name]}</svg>\`;
}
`,
);
