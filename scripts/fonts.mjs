// Bakes the pages' two typefaces into worker/runtime/http/assets/fontData.ts,
// so the Worker serves them itself and a page contacts no font host. Run
// `make icons` after changing FACES or bumping a @fontsource package.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

/** Latin subsets only: the pages are in English. */
const FACES = [
  { family: 'Atkinson Hyperlegible', pkg: 'atkinson-hyperlegible', weight: 400 },
  { family: 'Atkinson Hyperlegible', pkg: 'atkinson-hyperlegible', weight: 700 },
  { family: 'Fredoka', pkg: 'fredoka', weight: 500 },
  { family: 'Fredoka', pkg: 'fredoka', weight: 600 },
];

const entries = FACES.map(({ family, pkg, weight }) => {
  const bytes = readFileSync(`node_modules/@fontsource/${pkg}/files/${pkg}-latin-${weight}-normal.woff2`);
  // The name carries the content's hash, so a file can be cached for good.
  const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 10);
  return `  { family: '${family}', weight: ${weight}, path: '/fonts/${pkg}-${weight}.${hash}.woff2', base64: '${bytes.toString('base64')}' },`;
});

writeFileSync(
  'worker/runtime/http/assets/fontData.ts',
  `// Generated by scripts/fonts.mjs from @fontsource (SIL Open Font License 1.1). Do not edit; run \`make icons\`.

export interface FontFile {
  family: string;
  weight: number;
  path: string;
  base64: string;
}

export const FONT_FILES: FontFile[] = [
${entries.join('\n')}
];
`,
);
